"""
gen.py -- regenerate configs/ and manifest.tsv from arms.py. Idempotent.

    python experiments/time_head/gen.py

Each config is the CONTROL's capacity-sweep config read off disk verbatim, with its generated
header replaced and one line appended:

    time_head = True

Nothing is retyped. That is deliberate: the moment this file restated the schedule, the
"identical except one key" claim would depend on two files agreeing by hand, and the pairing
against the existing capacity runs would rot the first time either was touched. Regenerating
experiments/capacity/configs/ and re-running this script keeps them in lockstep, and
verify.py check [6] fails if the diff is ever anything but {time_head}.

out_dir and seed are injected at run time as CLI overrides, so one config serves all seeds
and both machines (the local run and the cluster).
"""
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)

from arms import (ARMS, SEEDS, control, overrides, why, shape, n_params,   # noqa: E402
                  head_params, manifest, CAP)

CAPCFG = os.path.join(CAP, "configs")

HEADER = '''\
# {arm} -- {n_params:,} params ({trunk:,} trunk + {head} added by this arm)
#
# {why}
#
# GENERATED by experiments/time_head/gen.py -- DO NOT EDIT BY HAND.
#
# Everything below this header is experiments/capacity/configs/cap_{control}.py, read
# verbatim, with these lines appended at the end and NOTHING else changed:
#     {ovsummary}
# So this arm and the capacity sweep's `{control}` arm differ in those keys only -- same
# dataset, same cohort filter, same schedule, same eval cadence, same seeds. The control is
# NOT re-run; it is experiments/capacity/runs/{control}_s<seed>. See arms.py for why that
# pairing is exact rather than approximate.
#
# out_dir and seed are supplied on the command line by the runner, not set here.
'''

TAIL = '''
# --- THE experimental variable(s) ----------------------------------------------------------
# {why}
{lines}'''


def control_body(ctl):
    """cap_<ctl>.py with its generated header comment block stripped.

    Strips only the LEADING run of comment/blank lines, so the inline comments further down
    ("--- THE swept variables ---", the cohort-filter note) survive. If the capacity config
    ever stops opening with a comment block this returns the whole file, which is still
    correct -- just with a duplicated header.
    """
    path = os.path.join(CAPCFG, f"cap_{ctl}.py")
    if not os.path.exists(path):
        sys.exit(f"[gen] missing control config {path}\n"
                 f"      run `python experiments/capacity/gen.py` first")
    lines = open(path).read().splitlines(True)
    i = 0
    while i < len(lines) and (lines[i].lstrip().startswith("#") or not lines[i].strip()):
        i += 1
    return "".join(lines[i:])


def main():
    cdir = os.path.join(HERE, "configs")
    os.makedirs(cdir, exist_ok=True)
    for arm in ARMS:
        ctl = control(arm)
        nl, nh, ne = shape(arm)
        hp, p = head_params(arm), n_params(arm)
        ov = overrides(arm)
        ovs = "  ".join(f"{k} = {v}" for k, v in ov.items())
        body = (HEADER.format(arm=arm, control=ctl, why=why(arm), n_params=p,
                              trunk=p - hp, head=hp, ovsummary=ovs)
                + control_body(ctl)
                + TAIL.format(why=why(arm),
                              lines="\n".join(f"{k} = {v}" for k, v in ov.items())))
        with open(os.path.join(cdir, f"th_{arm}.py"), "w") as f:
            f.write(body)
    print(f"wrote {len(ARMS)} configs -> {cdir}/")

    mpath = os.path.join(HERE, "manifest.tsv")
    with open(mpath, "w") as f:
        f.write("idx\tarm\tcontrol\tseed\tn_layer\tn_head\tn_embd\tn_params\n")
        for r in manifest():
            f.write("\t".join(str(x) for x in r) + "\n")
    print(f"wrote manifest -> {mpath}  ({len(manifest())} runs)")


if __name__ == "__main__":
    main()
