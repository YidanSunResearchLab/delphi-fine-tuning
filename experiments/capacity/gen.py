"""
gen.py -- regenerate configs/ and manifest.tsv from shapes.py. Idempotent.

    python experiments/capacity/gen.py

Configs contain ARCHITECTURE ONLY plus the frozen schedule. out_dir and seed are injected
at run time as CLI overrides, so one config serves all seeds and both machines (the local
smoke run and the cluster) without ever holding a machine-specific path.
"""
import os
from shapes import SHAPES, SEEDS, VOCAB_SIZE, BLOCK_SIZE, n_params, manifest

HERE = os.path.dirname(os.path.abspath(__file__))

# Frozen for every arm. Copied verbatim from config/train_delphi2m_mask_dedup.py except
# eval_interval (250 -> 100; see the note in shapes.py -- eval cadence perturbs the RNG
# stream, so it must be uniform across the sweep and cannot be left at the delivered value
# for some arms and not others).
TEMPLATE = '''\
# {tag} -- capacity sweep arm ({n_params:,} params, head_dim {hd})
#
# {why}
#
# GENERATED by experiments/capacity/gen.py from shapes.py -- DO NOT EDIT BY HAND.
#
# Everything below except n_layer / n_head / n_embd is identical to
# config/train_delphi2m_mask_dedup.py, with ONE documented exception: eval_interval is 100
# rather than 250, uniformly across every arm of the sweep. estimate_loss() draws its
# batches from the global torch RNG, so the eval cadence shifts the training batch stream;
# it has to be the same for all arms or the comparison is confounded. This is also why the
# delivered checkpoint (eval_interval=250, best at iter 2750) is NOT the reference here --
# the L12E120H12 arm of this sweep is.
#
# out_dir and seed are supplied on the command line by the runner, not set here.
dataset = "nacc-dedup-s42"

vocab_size = {vocab}
block_size = {block}

t_min = 365.25 / 12

ignore_tokens = list(range(22))

# --- THE swept variables ---
n_layer = {n_layer}
n_head = {n_head}
n_embd = {n_embd}

# --- frozen schedule ---
max_iters = 5000
batch_size = 128
learning_rate = 2e-3
lr_decay_iters = 5000
min_lr = 2e-4
warmup_iters = 500
beta2 = 0.99
dropout = 0.0
token_dropout = 0.0
weight_decay = 0.2
grad_clip = 1.0

eval_interval = 100
eval_iters = 200

# cohort filter left at train.py's defaults (4 / 2) -- the same 16,262-patient population
# the delivered model was fitted on. Not a swept variable.

wandb_project = "ad-projection"
'''


def main():
    cdir = os.path.join(HERE, "configs")
    os.makedirs(cdir, exist_ok=True)
    for tag, (nl, nh, ne, why) in SHAPES.items():
        body = TEMPLATE.format(tag=tag, why=why, n_layer=nl, n_head=nh, n_embd=ne,
                               vocab=VOCAB_SIZE, block=BLOCK_SIZE,
                               n_params=n_params(nl, nh, ne), hd=ne // nh)
        with open(os.path.join(cdir, f"cap_{tag}.py"), "w") as f:
            f.write(body)
    print(f"wrote {len(SHAPES)} configs -> {cdir}/")

    mpath = os.path.join(HERE, "manifest.tsv")
    with open(mpath, "w") as f:
        f.write("idx\ttag\tseed\tn_layer\tn_head\tn_embd\tn_params\n")
        for r in manifest():
            f.write("\t".join(str(x) for x in r) + "\n")
    print(f"wrote manifest -> {mpath}  ({len(manifest())} runs)")


if __name__ == "__main__":
    main()
